import type {
  ChangeSide,
  ExcludedPath,
  ExclusionReason,
  NormalizedReviewScope,
  ReviewUnit,
  RuleRef,
} from '../domain/types.js';
import type { DiffHunk } from '../git/diff.js';
import { matchesAnyGlob } from '../git/glob.js';
import { shortHash } from '../git/hash.js';
import { normalizeRepoPath } from '../git/paths.js';
import type { ChangeRecord } from './changes.js';
import { changePaths, changeSide, effectivePath } from './changes.js';
import { isProviderPath, isSecretPath, isTestPath } from './exclusions.js';

/** Bounds one file unit. An oversized hunk is sliced on raw diff-line boundaries. */
export const MAX_CHANGED_LINES_PER_UNIT = 400;

export interface PlanningOptions {
  scope: NormalizedReviewScope;
  maxChangedLinesPerUnit?: number;
  maxFileBytes?: number;
  ruleRefsForPath?: (path: string) => RuleRef[];
  relatedPathsForPath?: (path: string) => string[];
}

export interface UnitPlan {
  units: ReviewUnit[];
  excluded: ExcludedPath[];
}

interface HunkSlice {
  start: number;
  end: number;
}

/**
 * Converts changes into bounded file units plus one cross-file unit that is
 * generated by a fixed rule rather than left to an agent. Every changed path is
 * either planned or listed with an exclusion reason.
 */
export function planUnits(changes: readonly ChangeRecord[], options: PlanningOptions): UnitPlan {
  const scope = options.scope;
  const maxChanged = options.maxChangedLinesPerUnit ?? MAX_CHANGED_LINES_PER_UNIT;
  const maxFileBytes = options.maxFileBytes ?? 2 * 1024 * 1024;
  const units: ReviewUnit[] = [];
  const excluded: ExcludedPath[] = [];
  const includedPaths = new Set<string>();
  const includedChangeIds = new Set<string>();
  const includedChanges: ChangeRecord[] = [];
  const ruleRefs = new Map<string, RuleRef>();
  const relatedPaths = new Set<string>();

  for (const change of changes) {
    const path = effectivePath(change);
    const side = changeSide(change);
    const reason = exclusionReason(change, scope, maxFileBytes);
    if (reason !== undefined) {
      excluded.push({ path, side, reason, source: change.source });
      continue;
    }

    const paths = changePaths(change);
    for (const item of paths) {
      includedPaths.add(item);
    }
    includedChangeIds.add(change.changeId);
    includedChanges.push(change);

    const refs = options.ruleRefsForPath?.(path) ?? [];
    for (const ref of refs) {
      ruleRefs.set(`${ref.source}\0${ref.pattern}`, ref);
    }

    const related = new Set<string>();
    for (const item of paths) {
      for (const candidate of options.relatedPathsForPath?.(item) ?? []) {
        const normalized = normalizeRepoPath(candidate);
        if (normalized !== '' && !paths.includes(normalized)) {
          related.add(normalized);
          relatedPaths.add(normalized);
        }
      }
    }
    const relatedForUnit = [...related].sort(compare);
    const unitSide = side;

    if (change.hunks.length === 0) {
      units.push({
        unitId: `u_${shortHash(change.changeId, 'full')}`,
        kind: 'file',
        changeIds: [change.changeId],
        paths,
        relatedPaths: relatedForUnit,
        side: unitSide,
        startLine: 0,
        endLine: 0,
        slices: [],
        fullFile: true,
        ruleRefs: refs,
        status: 'pending',
      });
      continue;
    }

    change.hunks.forEach((hunk, hunkIndex) => {
      for (const slice of splitHunk(hunk, maxChanged)) {
        const [startLine, endLine] = sliceLines(hunk, slice);
        units.push({
          unitId: `u_${shortHash(change.changeId, hunk.header, String(slice.start), String(slice.end))}`,
          kind: 'file',
          changeIds: [change.changeId],
          paths,
          relatedPaths: relatedForUnit,
          side: unitSide,
          startLine,
          endLine,
          slices: [{ hunkIndex, start: slice.start, end: slice.end }],
          fullFile: false,
          ruleRefs: refs,
          status: 'pending',
        });
      }
    });
  }

  if (includedPaths.size > 0) {
    const paths = [...includedPaths].sort(compare);
    units.push({
      unitId: `u_cross_${shortHash(...paths)}`,
      kind: 'cross_file',
      changeIds: [...includedChangeIds].sort(compare),
      paths,
      relatedPaths: [...relatedPaths].filter((path) => !includedPaths.has(path)).sort(compare),
      side: crossFileSide(includedChanges),
      startLine: 0,
      endLine: 0,
      slices: [],
      fullFile: false,
      ruleRefs: [...ruleRefs.values()].sort(
        (left, right) => compare(left.source, right.source) || compare(left.pattern, right.pattern),
      ),
      status: 'pending',
    });
  }

  return { units, excluded: mergeExcluded(excluded) };
}

function exclusionReason(
  change: ChangeRecord,
  scope: NormalizedReviewScope,
  maxFileBytes: number,
): ExclusionReason | undefined {
  const path = effectivePath(change);
  if (path === '') {
    return 'unsupported';
  }
  // Credentials are never reviewable, even when explicitly included.
  if (isSecretPath(change.oldPath) || isSecretPath(change.newPath)) {
    return 'secret_path';
  }
  if (change.submodule) {
    return 'unsupported';
  }
  const userIncluded = matchesAnyGlob(scope.include, path);
  if (!userIncluded) {
    if (matchesAnyGlob(scope.exclude, path)) {
      return 'user_exclude';
    }
    if (isProviderPath(path) || isProviderPath(change.oldPath) || isProviderPath(change.newPath)) {
      return 'provider_directory';
    }
  }
  if (!scope.includeTests && isTestPath(path)) {
    return 'tests_excluded';
  }
  if (change.newPath === '' && !scope.includeDeleted) {
    return 'deleted_excluded';
  }
  if (change.binary) {
    return 'binary';
  }
  if (change.size > maxFileBytes) {
    return 'too_large';
  }
  return undefined;
}

function crossFileSide(changes: readonly ChangeRecord[]): ChangeSide {
  if (changes.length === 0) {
    return 'head';
  }
  if (changes.every((change) => change.newPath === '')) {
    return 'base';
  }
  return changes.some((change) => change.source === 'workspace' || change.source === 'untracked')
    ? 'workspace'
    : 'head';
}

/** Slices raw hunk lines into chunks of at most max changed lines. */
function splitHunk(hunk: DiffHunk, max: number): HunkSlice[] {
  const slices: HunkSlice[] = [];
  let start = 0;
  let changed = 0;
  for (let index = 0; index < hunk.lines.length; index += 1) {
    if (changed >= max) {
      slices.push({ start, end: index });
      start = index;
      changed = 0;
    }
    const line = hunk.lines[index] ?? '';
    if (line.length > 0 && (line[0] === '+' || line[0] === '-')) {
      changed += 1;
    }
  }
  if (start < hunk.lines.length) {
    slices.push({ start, end: hunk.lines.length });
  }
  if (slices.length === 0) {
    slices.push({ start: 0, end: hunk.lines.length });
  }
  return slices;
}

/** Maps a slice of raw hunk lines onto inclusive new-side line numbers. */
function sliceLines(hunk: DiffHunk, slice: HunkSlice): [number, number] {
  let newLine = hunk.newStart;
  let start = newLine;
  let end = newLine;
  const limit = Math.min(slice.end, hunk.lines.length);
  for (let index = 0; index < limit; index += 1) {
    const line = hunk.lines[index] ?? '';
    if (index === slice.start) {
      start = newLine;
    }
    if (line.length === 0 || line[0] !== '-') {
      end = newLine;
      newLine += 1;
    }
  }
  if (end < start) {
    end = start;
  }
  return [start, end];
}

function mergeExcluded(entries: readonly ExcludedPath[]): ExcludedPath[] {
  const seen = new Set<string>();
  const merged: ExcludedPath[] = [];
  for (const entry of entries) {
    const key = `${entry.path}\0${entry.side ?? ''}\0${entry.reason}`;
    if (seen.has(key)) {
      continue;
    }
    seen.add(key);
    merged.push(entry);
  }
  merged.sort(
    (left, right) =>
      compare(left.path, right.path) ||
      compare(left.side ?? '', right.side ?? '') ||
      compare(left.reason, right.reason),
  );
  return merged;
}

function compare(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}
